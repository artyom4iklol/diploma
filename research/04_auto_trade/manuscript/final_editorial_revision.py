def revise_text(content):
    records = []
    for prefix, revised in PARAGRAPHS:
        matches = [line for line in content.splitlines() if line.startswith(prefix)]
        assert len(matches) == 1, (prefix, len(matches))
        original = matches[0]
        assert re.findall(r'\[\^[^\]]+\]', original) == re.findall(r'\[\^[^\]]+\]', revised), prefix
        content = content.replace(original, revised)
        records.append({'anchor': prefix, 'before': original, 'after': revised,
                        'words_before': len(original.split()), 'words_after': len(revised.split())})
    assert 'после учёта предшествующей динамики и сезонности' not in content
    report = {'date': DATE, 'paragraphs_revised': len(records),
              'words_before': sum(x['words_before'] for x in records),
              'words_after': sum(x['words_after'] for x in records),
              'changes': records, 'publication_records': PUBLICATIONS,
              'source_check_scope': 'Publisher metadata verified; consulted-version locators retained explicitly. No claim that inaccessible final full texts were read.'}
    (HERE/'final_editorial_changes.json').write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n')
    return content
